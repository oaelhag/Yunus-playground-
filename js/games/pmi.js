function mul(a) { return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
const shuffle = (arr, r) => { for (let i = arr.length - 1; i > 0; i--) { const j = (r() * (i + 1)) | 0; [arr[i], arr[j]] = [arr[j], arr[i]]; } return arr; };

// نفس الترتيب للاعبين: المواقف تُخلط بالبذرة، وجمل كل موقف تبقى متتابعة تحت عنوان موقفها
function sequence(seed) {
  const r = mul(seed * 31 + 7), out = [];
  shuffle(SITUATIONS.map((_, k) => k), r).forEach((k) => {
    const [title, ...groups] = SITUATIONS[k];
    const sts = groups.flatMap((g, a) => g.map((t) => ({ t, a })));
    shuffle(sts, r).forEach((s) => out.push({ ctx: title, q: s.t, o: LABELS, a: s.a, why: WHY[s.a] }));
  });
  return out;
}

